/**
 * 记忆化一次异步读取：同一轮里多处要同一份状态时只读一次（issue #146 的扣下判定 + 推送后待裁决）。
 *
 * 为什么不是通用 memo：只服务「同一轮内必须看到**同一份**状态」这一个场景 —— 两处各读一次，
 * 中间被别的进程改写就会出现「扣下的」与「剔除的」不是同一批（真机后果：待裁决记错分区）。
 *
 * 语义（务必看清）：**reject 也被记忆化**。第一次失败后后续调用拿到同一个 rejected promise，
 * 不会重试 —— 这正是「同一份状态」的本意，重试反而会看到两份。调用方一律在 catch 侧兜底
 * （读不到就退化成安全的那一支），不要指望它替你重试。
 */
export function memoAsync<T>(fn: () => Promise<T>): () => Promise<T> {
  let pending: Promise<T> | undefined
  return () => (pending ??= fn())
}
